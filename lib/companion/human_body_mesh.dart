  /// Deforms base mesh vertices according to actual physical measurements
  /// and physiological anatomy, bounded to avoid unnatural stretching.
  static List<Vec3> computeMorphedVertices({
    required double heightCm,
    required double weightKg,
    double? waistCm,
    double? hipCm,
    double? chestCm,
    required BodyFrame frame,
    required double breathPhase,
    required bool isFemale,
  }) {
    // 1. Clamping to plausible physiological bounds
    final h = heightCm.clamp(135.0, 215.0);
    final w = weightKg.clamp(35.0, 185.0);

    // 2. Vertical height scaling (head size stays constant; limbs and spine scale)
    const refH = 172.0;
    const headBaseY = 146.0;
    final scaleY = (h - 26.0) / (refH - 26.0);

    // 3. BMI & Girth Ratio
    final hM = h / 100.0;
    final refW = 22.0 * (hM * hM); // reference weight at healthy BMI 22.0
    final weightRatio = (w / refW).clamp(0.70, 1.60);
    final girthBase = math.pow(weightRatio, 0.46).toDouble();

    // 4. Regional measurement ratios
    final waistRatio = waistCm != null
        ? (waistCm / (0.45 * h)).clamp(0.72, 1.50)
        : girthBase;
    final hipRatio = hipCm != null
        ? (hipCm / (0.57 * h)).clamp(0.72, 1.50)
        : girthBase * (isFemale ? 1.07 : 0.96);
    final chestRatio = chestCm != null
        ? (chestCm / (0.53 * h)).clamp(0.72, 1.45)
        : girthBase * (isFemale ? 1.04 : 1.0);

    // 5. Frame modifiers
    final frameScaleX = switch (frame) {
      BodyFrame.narrow => 0.93,
      BodyFrame.medium => 1.00,
      BodyFrame.broad => 1.07,
    };

    // 6. Respiration displacement
    final breathSin = math.sin(2.0 * math.pi * breathPhase);
    final breathChestZ = 0.85 * breathSin;
    final breathShoulderY = 0.35 * breathSin;

    final result = List<Vec3>.generate(baseVertices.length, (i) {
      final v = baseVertices[i];
      final y0 = v.y;
      final x0 = v.x;
      final z0 = v.z;

      // Vertical position
      double ny;
      if (y0 <= headBaseY) {
        ny = y0 * scaleY;
      } else {
        ny = headBaseY * scaleY + (y0 - headBaseY);
      }

      // Lateral and sagittal scaling based on anatomical zone
      double gx = girthBase;
      double gz = girthBase;

      // Waist region (y: 100 -> 118)
      if (y0 >= 95.0 && y0 <= 122.0) {
        final dist = (y0 - 110.0).abs() / 12.0;
        final blend = math.exp(-dist * dist * 1.5);
        gx = (1.0 - blend) * gx + blend * waistRatio;
        gz = (1.0 - blend) * gz + blend * waistRatio;
      }
      // Chest region (y: 118 -> 144)
      else if (y0 > 122.0 && y0 <= 145.0) {
        final dist = (y0 - 130.0).abs() / 12.0;
        final blend = math.exp(-dist * dist * 1.5);
        gx = (1.0 - blend) * gx + blend * chestRatio;
        gz = (1.0 - blend) * gz + blend * chestRatio;
        // Breathing expansion
        gz += breathChestZ * 0.15 * blend;
        ny += breathShoulderY * blend;
      }
      // Pelvis & Hips (y: 86 -> 100)
      else if (y0 >= 85.0 && y0 < 100.0) {
        final dist = (y0 - 92.0).abs() / 10.0;
        final blend = math.exp(-dist * dist * 1.5);
        gx = (1.0 - blend) * gx + blend * hipRatio;
        gz = (1.0 - blend) * gz + blend * hipRatio;
      }
      // Upper Thighs
      else if (y0 >= 55.0 && y0 < 85.0) {
        final thighG = math.pow(girthBase, 0.85).toDouble();
        gx = thighG;
        gz = thighG;
      }
      // Calves
      else if (y0 >= 16.0 && y0 < 55.0) {
        final calfG = math.pow(girthBase, 0.65).toDouble();
        gx = calfG;
        gz = calfG;
      }
      // Head / Neck / Shoes do not swell excessively with weight
      else if (y0 > 145.0) {
        gx = 1.0 + (girthBase - 1.0) * 0.18; // soft cheeks
        gz = 1.0 + (girthBase - 1.0) * 0.18;
      } else {
        gx = 1.0;
        gz = 1.0;
      }

      // Apply frame width to shoulders and hips
      double nx = x0 * gx;
      if (y0 >= 80.0 && y0 <= 150.0) {
        nx *= frameScaleX;
      } else if (y0 < 80.0 && x0.abs() > 4.0) {
        // Leg stances shift slightly with frame width
        final legSign = x0 > 0 ? 1.0 : -1.0;
        nx += legSign * (frameScaleX - 1.0) * 1.2;
      }

      double nz = z0 * gz;
      return Vec3(nx, ny, nz);
    });

    return result;
  }
